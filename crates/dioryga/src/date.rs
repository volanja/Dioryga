//! 画面から入った日付の読み取り。
//!
//! # 区切りは `-` と `/` の両方を受ける
//!
//! `<input type="date">` は送信時には必ず `2026-09-23` を送るが、**画面に見えて
//! いるのは `2026/09/23` である**（日本語の環境）。日付入力に対応していない
//! ブラウザでは普通の文字欄になり、利用者は見えている形のまま `2026/09/23` と
//! 打つ。**見えている形で入れたものを拒否すると、何が悪いのか分からない**
//! ——#180 の登録画面で実際に起きた。
//!
//! 月と日の0埋めは問わない（`2026/9/3` も読む）。
//!
//! **取込（CSV）はこの関数を使わない。**取込の形式は設計書23章が決めており、
//! 画面の寛容さを取込へ持ち込むと、ファイルの書き方が画面の都合で揺れる。

use chrono::NaiveDate;

/// 読めなければ `None`。**空欄も `None`**——空かどうかは呼び出し側が先に見る。
pub fn 読む(value: &str) -> Option<NaiveDate> {
    let v = value.trim();
    ["%Y-%m-%d", "%Y/%m/%d"]
        .iter()
        .find_map(|f| NaiveDate::parse_from_str(v, f).ok())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn d(y: i32, m: u32, day: u32) -> Option<NaiveDate> {
        NaiveDate::from_ymd_opt(y, m, day)
    }

    #[test]
    fn 送信される形も見えている形も読む() {
        assert_eq!(読む("2026-09-23"), d(2026, 9, 23));
        assert_eq!(読む("2026/09/23"), d(2026, 9, 23));
        assert_eq!(読む(" 2026/9/3 "), d(2026, 9, 3));
    }

    #[test]
    fn 読めないものは読まない() {
        assert_eq!(読む(""), None);
        assert_eq!(読む("2026/13/01"), None);
        assert_eq!(読む("2026.09.23"), None);
        assert_eq!(読む("23/09/2026"), None);
    }
}
